"""Knowledge Foundation Builder — PSO bootstraps, cognition replaces it entirely.

Part 15: PSO is a scaffolding tool, not a permanent crutch.

    Infant (no knowledge):       PSO explores widely → seeds the knowledge base
    Adolescent (some knowledge): PSO narrows, reasoning grows alongside it
    Mature (solid knowledge):    Reasoning dominates, PSO fills last gaps
    Expert (rich knowledge):     ZERO PSO. Cognition handles everything.
                                 Novelty comes from hypothesis generation,
                                 causal experiments, formula invention, and
                                 investigation — not random search.

The key philosophical principle: A real intelligence does not dice-roll
at the expert level. It reasons about what it doesn't know and designs
targeted experiments to fill those gaps. PSO exists only to bootstrap
the mind — once the mind is built, PSO is no longer needed.
"""

from __future__ import annotations
import numpy as np


class KnowledgeFoundationBuilder:
    """Orchestrates the transition from PSO exploration to pure reasoning.

    At expert level, PSO drops to ZERO. Novelty is generated by the
    cognitive systems themselves:
        - Causal Intervention → designs targeted experiments
        - Formula Engine → invents new mathematical models
        - Investigation Engine → explores failure modes
        - Network Traversal → discovers new reasoning paths

    PSO is scaffolding. You remove scaffolding once the building stands.
    """

    # Maturity thresholds
    INFANT_THRESHOLD = 0.2      # Below this: PSO dominates
    ADOLESCENT_THRESHOLD = 0.5  # PSO and reasoning share equally
    MATURE_THRESHOLD = 0.8      # Reasoning dominates, PSO fills gaps
    # Above MATURE: Expert — ZERO PSO, pure cognition

    # M0.4 (v22 blueprint §4.2): detachment is earned by demonstrated
    # prediction skill -- the rolling fraction of applied principles
    # whose configs actually helped -- not by knowledge quantity.
    SKILL_WINDOW = 30        # principle applications remembered
    MIN_SKILL_EVIDENCE = 10  # applications needed before skill counts
    SKILL_GATE = 0.6         # hit rate below this can never reach MATURE

    def __init__(self):
        self._knowledge_maturity: float = 0.0
        self._total_principles: int = 0
        self._total_episodes: int = 0
        self._recent_r2_scores: list[float] = []
        self._warm_start_weights: np.ndarray | None = None
        # M0.4: helped/hurt outcome of each principle application
        self._principle_outcomes: list[bool] = []
        # Last components of the (Category-D, hand-weighted) maturity blend,
        # populated by update_maturity for audit Part E telemetry.
        self._last_maturity_components: dict = {}
        # Opt-in non-saturating count normalization -- see _count_score.
        # Set from cfg.maturity_soft_normalization by the optimizer.
        self.soft_normalization: bool = False

    def _count_score(self, count: float, cap: float) -> float:
        """Normalize a knowledge-QUANTITY count into [0, 1].

        Default (`soft_normalization = False`) is the historical
        `min(1, count/cap)` -- byte-identical to before.

        MEASURED 2026-07-24 (audit Part E, Category D): that form is
        STRUCTURALLY guaranteed to go dead in a lifelong-learning system,
        which is what UIL claims to be. Against the real production store
        every one of these terms is pinned at exactly 1.0 --
        principles 201/50, network nodes 300/30, episodes 135/20,
        formulas 32/10 -- so all four have std 0 and carry ZERO signal
        into the maturity blend that gates PSO detachment. In isolated
        runs they are dead at the other end (~0). Dead in both regimes.

        `soft_normalization = True` swaps in `count / (count + cap)`:
        same [0,1] range, same monotonicity, same "cap sets the scale"
        meaning (at count == cap it reads 0.5), but it approaches 1
        asymptotically and NEVER saturates -- so the term keeps a nonzero
        derivative at any store size. Stateless and deterministic, so it
        needs no persisted running statistic and does not touch replay.
        On the production counts above it yields 0.80 / 0.91 / 0.87 /
        0.76 instead of 1.0 / 1.0 / 1.0 / 1.0 -- signal restored.

        OPT-IN (default off) because it materially rescales maturity --
        at count == cap it reads 0.5 where the old form read 1.0 -- and
        maturity gates PSO detachment, so it must clear a cross-seed gate
        before shipping on (the E6 lesson).
        """
        cap = float(cap) if cap else 1.0
        c = max(0.0, float(count))
        if getattr(self, "soft_normalization", False):
            return c / (c + cap)
        return min(1.0, c / cap)

    def record_principle_outcome(self, helped: bool) -> None:
        """M0.4: record whether an applied principle's prediction won.

        Fed by the optimizer's triggered-principle credit loop (same
        helped signal that library.record_application receives).
        """
        self._principle_outcomes.append(bool(helped))
        if len(self._principle_outcomes) > self.SKILL_WINDOW:
            self._principle_outcomes = self._principle_outcomes[-self.SKILL_WINDOW:]

    @property
    def principle_hit_rate(self) -> float | None:
        """Rolling hit rate of applied principles; None until enough evidence."""
        if len(self._principle_outcomes) < self.MIN_SKILL_EVIDENCE:
            return None
        return float(np.mean(self._principle_outcomes))

    def set_warm_start_weights(self, weights: np.ndarray | None) -> None:
        if weights is None:
            return
        w = np.asarray(weights, dtype=float)
        self._warm_start_weights = np.clip(w, 0.0, 1.0)

    # ── Maturity Estimation ─────────────────────────────────────────

    def update_maturity(
        self,
        n_principles: int,
        n_episodes: int,
        n_formulas: int,
        miner_r2: float,
        network_nodes: int,
        recent_accuracy: float,
    ) -> float:
        """Compute knowledge maturity from multiple signals.

        Signals:
            1. Principle count: more rules = more knowledge
            2. Episode count: more past cases = better warm-start
            3. Formula count: invented formulas = deeper understanding
            4. Miner R²: high R² = we understand what causes regret
            5. Network size: more nodes = richer reasoning graph
            6. Recent accuracy: high accuracy = knowledge is working

        Returns:
            Maturity score in [0, 1].
        """
        self._total_principles = n_principles
        self._total_episodes = n_episodes

        # Track miner R² history
        self._recent_r2_scores.append(miner_r2)
        if len(self._recent_r2_scores) > 20:
            self._recent_r2_scores = self._recent_r2_scores[-20:]

        # Component scores (each in [0, 1])
        principle_score = self._count_score(n_principles, 50)
        episode_score = self._count_score(n_episodes, 20)
        formula_score = self._count_score(n_formulas, 10)
        r2_score = np.clip(miner_r2, 0.0, 1.0)
        network_score = self._count_score(network_nodes, 30)
        accuracy_score = np.clip(recent_accuracy, 0.0, 1.0)

        # Weighted combination (principle count and R² matter most)
        legacy_blend = (
            0.25 * principle_score
            + 0.10 * episode_score
            + 0.10 * formula_score
            + 0.25 * r2_score
            + 0.15 * network_score
            + 0.15 * accuracy_score
        )

        # M0.4 (v22 blueprint §4.2): maturity is keyed to demonstrated
        # prediction skill. Rationale: the quantity blend above measures
        # how much the system KNOWS, not whether that knowledge PREDICTS.
        # Detachment (dropping PSO) is only safe -- and only deserved --
        # when applied principles' configs actually win. Two effects:
        #   1. Without >= MIN_SKILL_EVIDENCE principle outcomes, or with a
        #      hit rate below SKILL_GATE, maturity is capped just below
        #      MATURE: PSO can never fully detach on accumulation alone.
        #   2. With demonstrated skill, the skill term carries 40% weight,
        #      so detachment becomes REACHABLE with a half-built knowledge
        #      base -- fixing the "detachment never fires" defect.
        hit_rate = self.principle_hit_rate
        if hit_rate is not None:
            skill_score = float(np.clip((hit_rate - 0.5) / 0.4, 0.0, 1.0))
            # Quantity evidence, accuracy factored out (renormalized 0.85)
            evidence_score = (
                0.25 * principle_score
                + 0.10 * episode_score
                + 0.10 * formula_score
                + 0.25 * r2_score
                + 0.15 * network_score
            ) / 0.85
            maturity = (
                0.35 * evidence_score
                + 0.40 * skill_score
                + 0.25 * accuracy_score
            )
            if hit_rate < self.SKILL_GATE:
                maturity = min(maturity, self.MATURE_THRESHOLD - 0.05)
        else:
            maturity = min(legacy_blend, self.MATURE_THRESHOLD - 0.05)

        self._knowledge_maturity = float(np.clip(maturity, 0.0, 1.0))

        # Category-D telemetry (audit Part E): the maturity blend weights
        # (0.35/0.40/0.25 on the skill path, the 6-term legacy_blend
        # otherwise) are hand-picked and never fit to data. Store every
        # component so a consumer can log its distribution and spot a DEAD
        # sub-score — e.g. formula_score or network_score stuck at 0 would
        # make its weight contribute nothing to the PSO-detachment decision.
        self._last_maturity_components = {
            "principle_score": float(principle_score),
            "episode_score": float(episode_score),
            "formula_score": float(formula_score),
            "r2_score": float(r2_score),
            "network_score": float(network_score),
            "accuracy_score": float(accuracy_score),
            "skill_score": (
                float(skill_score) if hit_rate is not None else float("nan")
            ),
            "maturity": self._knowledge_maturity,
        }
        return self._knowledge_maturity

    # ── Exploration Budget ──────────────────────────────────────────

    @property
    def exploration_ratio(self) -> float:
        """How much of the search should be PSO vs reasoning.

        Returns a ratio in [0.0, 1.0]:
            1.0 = 100% PSO exploration (infant)
            0.5 = 50/50 split (adolescent)
            ~0.1 = mostly reasoning (mature)
            0.0 = ZERO PSO (expert) — pure cognition
        """
        m = self._knowledge_maturity
        if m >= self.MATURE_THRESHOLD:
            # Expert: zero PSO. The mind is built.
            return 0.0
        # Smooth exponential decay from 1.0 → 0.0
        ratio = np.exp(-3.5 * m)
        return float(np.clip(ratio, 0.0, 1.0))

    @property
    def reasoning_ratio(self) -> float:
        """How much reasoning should drive the search."""
        return 1.0 - self.exploration_ratio

    # ── Action Allocation ───────────────────────────────────────────

    def allocate_actions(self, max_actions: int = 6) -> dict:
        """Decide how many PSO vs reasoning actions to generate.

        At expert level: 0 PSO, all reasoning + cognitive novelty.

        Returns:
            {"pso_actions": int, "reasoning_actions": int,
             "cognitive_novelty": int, "stage": str}
        """
        m = self._knowledge_maturity

        # Determine stage
        if m < self.INFANT_THRESHOLD:
            stage = "infant"
        elif m < self.ADOLESCENT_THRESHOLD:
            stage = "adolescent"
        elif m < self.MATURE_THRESHOLD:
            stage = "mature"
        else:
            stage = "expert"

        if stage == "expert":
            # ZERO PSO. All cognitive.
            # Split between standard reasoning and cognitive novelty
            # (hypothesis-driven, causal experiment, formula invention)
            reasoning = max_actions - 1  # Leave 1 slot for cognitive novelty
            cognitive = 1
            pso = 0
        elif stage == "mature":
            # Minimal PSO, mostly reasoning
            pso = 1
            cognitive = 0
            reasoning = max_actions - pso
        elif stage == "adolescent":
            # Balanced
            ratio = self.exploration_ratio
            pso = max(1, int(round(max_actions * ratio)))
            reasoning = max_actions - pso
            cognitive = 0
        else:
            # Infant: PSO dominates, but ensure at least 1 reasoning
            # if we have ANY knowledge at all
            ratio = self.exploration_ratio
            pso = max(1, int(round(max_actions * ratio)))
            reasoning = max_actions - pso
            cognitive = 0
            if m > 0.05 and reasoning < 1:
                reasoning = 1
                pso = max_actions - 1

        return {
            "pso_actions": pso,
            "reasoning_actions": reasoning,
            "cognitive_novelty": cognitive,
            "stage": stage,
            "maturity": round(m, 3),
            "exploration_ratio": round(self.exploration_ratio, 3),
        }

    # ── Foundation Exploration (PSO — infant/adolescent only) ───────

    def get_foundation_targets(
        self,
        state: dict,
        n_features: int,
        rng: np.random.Generator,
    ) -> list[dict]:
        """Generate PSO exploration for foundation building.

        Only called during infant/adolescent/mature stages.
        Returns EMPTY at expert level — no random search ever.
        """
        allocation = self.allocate_actions()
        n_pso = allocation["pso_actions"]

        if n_pso == 0:
            return []  # Expert: zero PSO. The mind reasons.

        targets = []

        if allocation["stage"] == "infant":
            # Wide exploration: uniform random + structured sweeps
            for i in range(n_pso):
                if (
                    i == 0
                    and self._warm_start_weights is not None
                    and len(self._warm_start_weights) == n_features
                ):
                    w = np.clip(
                        self._warm_start_weights + rng.normal(0, 0.06, n_features),
                        0.0, 1.0,
                    )
                elif i == 0:
                    w = rng.uniform(0.0, 1.0, n_features)
                elif i == 1:
                    # Sparse: only keep top-30% features
                    w = rng.uniform(0.0, 1.0, n_features)
                    threshold = np.percentile(w, 70)
                    w[w < threshold] = 0.0
                elif i == 2:
                    # Dense: all features moderate
                    w = rng.uniform(0.3, 0.7, n_features)
                else:
                    # Extreme: very sparse or very dense
                    if rng.random() > 0.5:
                        w = np.zeros(n_features)
                        idx = rng.choice(
                            n_features, size=max(1, n_features // 5),
                            replace=False,
                        )
                        w[idx] = rng.uniform(0.5, 1.0, len(idx))
                    else:
                        w = rng.uniform(0.5, 1.0, n_features)

                targets.append({
                    "feature_weights": np.clip(w, 0.0, 1.0),
                    "penalty": rng.uniform(0.5, 3.0),
                    "description": f"Foundation exploration (infant, variant {i})",
                })

        elif allocation["stage"] == "adolescent":
            # Targeted: explore with focused perturbations
            for i in range(n_pso):
                scale = 0.2 + 0.3 * rng.random()
                noise = rng.normal(0, scale, n_features)
                base = rng.uniform(0.2, 0.8, n_features)
                w = np.clip(base + noise, 0.0, 1.0)
                targets.append({
                    "feature_weights": w,
                    "penalty": rng.uniform(0.8, 2.5),
                    "description": f"Foundation exploration (adolescent, variant {i})",
                })

        elif allocation["stage"] == "mature":
            # Last-mile gap filling: single targeted probe
            for i in range(n_pso):
                w = rng.uniform(0.3, 0.7, n_features)
                targets.append({
                    "feature_weights": np.clip(w, 0.0, 1.0),
                    "penalty": rng.uniform(1.0, 2.0),
                    "description": f"Gap filling (mature, variant {i})",
                })

        return targets

    # ── Cognitive Novelty (Expert-level — replaces PSO entirely) ────

    def get_cognitive_novelty_request(self) -> dict:
        """Request cognitive novelty generation at expert level.

        Instead of random PSO particles, the cognitive systems generate
        novelty through their own mechanisms:
            1. Causal Intervention → design an experiment to test a
               hypothesis about an uncertain principle
            2. Formula Engine → generate a new formula variant
            3. Investigation Engine → probe a known weak area
            4. Counter-factual → invert a known principle to test robustness

        Returns a request dict that the optimizer routes to the
        appropriate cognitive module.
        """
        allocation = self.allocate_actions()
        if allocation["cognitive_novelty"] == 0:
            return {"type": "none"}

        return {
            "type": "cognitive_novelty",
            "strategies": [
                "causal_experiment",     # Design a targeted test
                "formula_invention",     # Try a new mathematical model
                "weakness_investigation", # Probe known failure modes
                "counter_factual",       # What if the opposite is true?
            ],
            "description": (
                "Expert-level novelty: UIL generates its own experiments "
                "through reasoning, not random search."
            ),
        }

    # ── Diagnostics ────────────────────────────────────────────────

    @property
    def maturity(self) -> float:
        return self._knowledge_maturity

    def get_summary(self) -> dict:
        allocation = self.allocate_actions()
        return {
            "maturity": round(self._knowledge_maturity, 3),
            "stage": allocation["stage"],
            "exploration_ratio": allocation["exploration_ratio"],
            "pso_actions": allocation["pso_actions"],
            "reasoning_actions": allocation["reasoning_actions"],
            "cognitive_novelty": allocation["cognitive_novelty"],
            "pso_fully_detached": allocation["pso_actions"] == 0,
            "principles_seen": self._total_principles,
            "episodes_seen": self._total_episodes,
        }
