"""UIL Principle Library — Machine-discovered principles only.

NO manually injected principles (P-002, P-003 are gone).
Every principle is discovered by the Miner from journal data.

Principles have:
- Conditions (machine-discovered thresholds)
- Action overrides (auto-generated by inverting the cause)
- Confidence + evidence tracking
- Decay (bad principles die naturally)
- Cross-classifier validation
- V20+.1: 4-Tier Hierarchy (Universal, Category, Dataset-Specific, Exception)
- V20+.6: Seed Knowledge — human-provided initial principles as hypotheses
"""

from __future__ import annotations
import os
import json
import numpy as np
from datetime import datetime, timezone

from figpso_uil.cognition.paths import results_path
from figpso_uil.cognition.version_store import VersionStore

from figpso_uil.cognition.condition_match import (
    PENALTY_FEATURES,
    condition_sets_similar,
    sanitize_overrides,
)
from figpso_uil.cognition.principle_hierarchy import (
    PrincipleHierarchy,
    TIER_DATASET_SPECIFIC,
    TIER_EXCEPTION,
    TIER_NAMES,
)


class UIL_Library:
    """Stores and manages machine-discovered principles.
    
    A principle is a rule discovered from data, never manually written:
    {
        "principle_id": "P-001",
        "conditions": [
            {"feature": "action.penalty", "op": ">", "threshold": 2.14},
            {"feature": "state.n_samples", "op": "<=", "threshold": 47}
        ],
        "action_override": {"max_penalty": 2.14},
        "predicted_regret": 2.1,
        "confidence": 0.89,
        "evidence_count": 34,
        "mining_level": "within_dataset",
        "classifiers_confirmed": ["XGBoost"],
        "times_applied": 0,
        "times_helped": 0,
        "discovered_at": "2026-06-07T..."
    }
    """

    # Promotion thresholds
    MIN_CONFIDENCE = 0.75
    MIN_EVIDENCE = 10

    # Decay parameters
    DECAY_MIN_APPLICATIONS = 20
    DECAY_HELP_RATIO = 0.3  # Must help >30% of the time to survive

    def __init__(
        self,
        library_path: str = results_path("uil_principles_v19.json"),
        version_store: VersionStore | None = None,
    ):
        self.library_path = library_path
        self._version_store = version_store
        self._ensure_file()
        self.hierarchy = PrincipleHierarchy()

    # ── Core Methods ─────────────────────────────────────────────────

    def get_principles(
        self,
        dataset_name: str | None = None,
        max_tier: int = TIER_DATASET_SPECIFIC,
    ) -> list[dict]:
        """Get active principles, filtered by tier and quarantine.

        V20+.1: Tier-aware retrieval. Quarantined principles for the
        given dataset are excluded. Sorted by tier (Universal first).

        Args:
            dataset_name: Current dataset (for quarantine filtering).
            max_tier: Maximum tier to include (1=universal only, 3=all).

        Returns:
            Filtered, tier-sorted list of active principles.
        """
        principles = self._load()
        return self.hierarchy.filter_by_tier(
            principles, max_tier=max_tier, dataset_name=dataset_name
        )

    def _cell_store(self) -> VersionStore | None:
        if self._version_store is not None:
            return self._version_store
        try:
            return VersionStore.shared()
        except Exception:
            return None

    def _log_cell(self, principle: dict, op: str, cause: str | None = None) -> None:
        store = self._cell_store()
        if store is None:
            return
        store.record_cell(
            cell_id=principle.get("principle_id", "?"),
            cell_type=principle.get("cell_type", "principle"),
            op=op,
            post_state=principle,
            cause=cause,
        )

    def record_routing_rule(
        self,
        *,
        dataset_name: str,
        domain: str,
        strategy: str,
        source: str,
        fingerprint_id: str | None = None,
    ) -> dict:
        """Mint a routing_rule cell (Category tier) with provenance."""
        rid = f"RR-{domain}-{strategy}"
        rule = {
            "principle_id": rid,
            "cell_type": "routing_rule",
            "conditions": [
                {"feature": "dataset.name", "op": "==", "threshold": dataset_name},
                {"feature": "route.domain", "op": "==", "threshold": domain},
            ],
            "action_override": {"preferred_strategy": strategy},
            "confidence": 0.55,
            "evidence_count": 1,
            "mining_level": "routing",
            "source": source,
            "fingerprint_id": fingerprint_id,
            "tier": 2,
            "discovered_at": datetime.now(timezone.utc).isoformat(),
        }
        principles = self._load()
        existing = self._find_similar(principles, rule)
        if existing is not None:
            p = principles[existing]
            p["evidence_count"] = p.get("evidence_count", 0) + 1
            p["confidence"] = min(0.95, p.get("confidence", 0.5) + 0.03)
            p["action_override"] = rule["action_override"]
        else:
            principles.append(rule)
        self._save(principles)
        self._log_cell(rule, op="create", cause=f"route:{source}")
        return rule

    def update_principles(
        self, mined_rules: list[dict], min_evidence: int | None = None,
    ) -> None:
        """Promote mined rules to principles if they meet thresholds.

        Also applies decay to existing principles that aren't helping.

        `min_evidence` overrides MIN_EVIDENCE for this call. MEASURED
        2026-07-23: a rule's `evidence_count` is its decision-tree leaf
        size, which is bounded by the journal, so the fixed threshold of
        10 needs roughly **200 same-dataset stages** before ANY rule can
        be promoted (at 100 journal entries the largest leaf holds 9 --
        one short). Since experiment and audit runs use an isolated
        `state_dir`, their journal starts empty and NO principle is ever
        mined; the library contains only bootstrap seeds, which emit
        `max_penalty` alone. That is a third unreachable threshold of the
        same shape as the evolution stress gate, and it is why the
        existence audit reads INERT regardless of what vocabulary the
        miner is capable of emitting.

        Lowering it is an EPISTEMOLOGY change (weaker evidence admits
        more false principles), not a wiring fix, so it is opt-in via
        `cfg.adaptive_min_evidence` and must clear a cross-seed gate
        before becoming the default -- the E6 lesson.
        """
        threshold = self.MIN_EVIDENCE if min_evidence is None else max(3, int(min_evidence))
        principles = self._load()

        # 1. Try to promote new rules
        for rule in mined_rules:
            if (
                rule.get("confidence", 0) >= self.MIN_CONFIDENCE
                and rule.get("evidence_count", 0) >= threshold
            ):
                # Check if a similar principle already exists
                existing = self._find_similar(principles, rule)
                if existing is not None:
                    # Update existing principle with new evidence
                    self._merge_evidence(principles[existing], rule)
                else:
                    # Create new principle
                    new_principle = self._create_principle(rule, len(principles))
                    principles.append(new_principle)
                    self._log_cell(new_principle, op="create", cause="miner")

        principles = self._apply_decay(principles)

        self._save(principles)

    def record_application(
        self,
        principle_id: str,
        helped: bool,
        classifier: str,
        dataset_name: str = "",
    ) -> None:
        """Record that a principle was applied.

        Used to track times_applied and times_helped for decay.
        Also tracks which classifiers it works with.
        V20+.1: Also records per-dataset performance for tier management.
        """
        principles = self._load()
        for p in principles:
            if p["principle_id"] == principle_id:
                p["times_applied"] = p.get("times_applied", 0) + 1
                if helped:
                    p["times_helped"] = p.get("times_helped", 0) + 1
                # Track classifier confirmation
                confirmed = p.get("classifiers_confirmed", [])
                if classifier not in confirmed:
                    confirmed.append(classifier)
                    p["classifiers_confirmed"] = confirmed
                    # Cross-classifier boost: confirmed on multiple classifiers
                    if len(confirmed) > 1:
                        boost = 0.02 * (len(confirmed) - 1)
                        p["confidence"] = min(0.99, p["confidence"] + boost)

                # V20+.1: Per-dataset tracking for hierarchy
                if dataset_name:
                    self.hierarchy.record_application(
                        principle_id, dataset_name, helped
                    )

                break
        self._save(principles)

    def apply_causal_adjustment(
        self, rule_conditions: list[dict], multiplier: float
    ) -> str | None:
        """Adjust a principle's confidence after causal intervention testing.

        Called once CausalInterventionEngine.evaluate_intervention() has
        a verdict for the hypothesis derived from this rule. Confirmed
        causal → multiplier > 1 boosts confidence; refuted → multiplier
        < 1 sharply cuts it. Without this hook, intervention results
        never reach the principle that spawned the hypothesis.

        Returns the adjusted principle_id, or None if no match exists yet
        (e.g. the rule hasn't crossed the promotion threshold).
        """
        principles = self._load()
        idx = self._find_similar(principles, {"conditions": rule_conditions})
        if idx is None:
            return None
        p = principles[idx]
        p["confidence"] = float(np.clip(p.get("confidence", 0.5) * multiplier, 0.05, 0.99))
        self._save(principles)
        return p["principle_id"]

    def all_principles_exhausted(self) -> bool:
        """Check if all principles have been tried sufficiently.

        Used by StressEngine to determine failure.
        """
        principles = self._load()
        if not principles:
            return True  # No principles = exhausted by definition
        return all(p.get("times_applied", 0) >= 3 for p in principles)

    # ── V20+.6: Seed Knowledge ──────────────────────────────────────

    def accept_seed_principles(self, seeds: list[dict]) -> int:
        """Accept human-provided seed knowledge as hypotheses.

        Seed principles are treated as INITIAL HYPOTHESES, not ground truth.
        They start with:
            - confidence = 0.5 (neutral — neither trusted nor distrusted)
            - source = "seed"
            - tier = TIER_DATASET_SPECIFIC (must earn promotion)

        The system can challenge, override, or discard them as it
        accumulates its own evidence. Like a teacher giving a student
        initial rules, then the student proving some wrong.

        Args:
            seeds: List of seed principle dicts, each containing:
                - conditions: list of {feature, op, threshold}
                - action_override: dict of overrides
                - description: (optional) human-readable explanation

        Returns:
            Number of seed principles accepted.
        """
        principles = self._load()
        count = 0

        for seed in seeds:
            conditions = seed.get("conditions", [])
            if not conditions:
                continue

            # Skip if similar principle already exists
            if self._find_similar(principles, seed) is not None:
                continue

            principle = {
                "principle_id": f"P-{len(principles) + 1:03d}",
                "tier": TIER_DATASET_SPECIFIC,  # Must earn promotion
                "conditions": conditions,
                "action_override": seed.get("action_override", {}),
                "predicted_regret": seed.get("predicted_regret", 0.0),
                "confidence": 0.5,  # Neutral — not trusted yet
                "evidence_count": 0,
                "mining_level": "seed",
                "source": "seed",
                "classifiers_confirmed": [],
                "times_applied": 0,
                "times_helped": 0,
                "description": seed.get("description", ""),
                "discovered_at": datetime.now(timezone.utc).isoformat(),
            }
            principles.append(principle)
            count += 1

        if count > 0:
            self._save(principles)

        return count

    # ── Internal ─────────────────────────────────────────────────────

    def _create_principle(self, rule: dict, current_count: int) -> dict:
        """Create a new principle from a mined rule.

        Auto-generates action overrides by INVERTING the discovered cause.
        If the tree finds 'penalty > 2.14 → high regret',
        the override is 'cap penalty at 2.14'.

        V20+.1: Assigns initial tier via the hierarchy.
        """
        # V20+.1: Assign initial tier
        initial_tier = self.hierarchy.assign_initial_tier(rule)

        principle = {
            "principle_id": f"P-{current_count + 1:03d}",
            "tier": initial_tier,
            "conditions": rule["conditions"],
            "action_override": self._generate_override(rule["conditions"]),
            "predicted_regret": rule.get("predicted_regret", 0.0),
            "confidence": rule.get("confidence", 0.0),
            "evidence_count": rule.get("evidence_count", 0),
            "mining_level": rule.get("mining_level", "unknown"),
            "dataset": rule.get("dataset"),
            # F6 — logging-policy footnote from the miner (HITL confound visibility).
            "logging_policy": rule.get("logging_policy"),
            "classifiers_confirmed": [],
            "times_applied": 0,
            "times_helped": 0,
            "tier_history": [],
            "discovered_at": datetime.now(timezone.utc).isoformat(),
        }
        return principle

    # Classifier-config keys a principle must NEVER constrain.
    #
    # `learning_mode` is architecture chosen by the domain router or the
    # operator; bug #21's invariant forbids a per-stage mechanism resetting
    # it (the adapter locks it anyway, so an override here would be a
    # silent no-op that still pollutes the journal). `parallel_eval_workers`
    # is a machine-resource knob with no bearing on model quality, and
    # constraining it would make mined knowledge machine-specific.
    NON_CONSTRAINABLE_CONFIG = frozenset({
        "learning_mode",
        "parallel_eval_workers",
    })

    # The feature names that ARE the penalty knob. Exact matching, not
    # `"penalty" in feature`.
    #
    # MEASURED on the production graph (2026-07-23): the old substring
    # test also matched the miner's DERIVED features -- e.g.
    # `derived.action.penalty*config.mutation_rounds_per_fit` -- and
    # treated a threshold on a PRODUCT as a threshold on penalty itself.
    # 18 of 300 live nodes carry the result: `min_penalty: 1270.45`,
    # `max_penalty: 0.0003`. Penalty is proposed in 0.5-3.0 and clamped
    # to [0,10], so those bounds are nonsense. The same bug family as
    # #14, where derived variables leaked into the causal scheduler.
    PENALTY_FEATURES = PENALTY_FEATURES

    # A penalty bound outside the knob's own domain is not a constraint,
    # it is corrupt data -- see PENALTY_FEATURES. Applied on INGEST as
    # well as on generation, because the graph already contains poisoned
    # nodes from before the generator was fixed.
    PENALTY_BOUND_RANGE = (0.0, 10.0)

    # Shared with the knowledge graph -- see condition_match.
    sanitize_overrides = staticmethod(sanitize_overrides)

    def _generate_override(self, conditions: list[dict]) -> dict:
        """Auto-generate action overrides by inverting a mined condition.

        If a condition says 'action.penalty > 2.14 -> high regret', then
        the override is 'max_penalty = 2.14' (cap it).

        Conditions on state ('state.entropy <= 0.08 -> bad') describe the
        world rather than our behaviour: they cannot be acted on and stay
        as context. Only conditions on things we CONTROL become overrides.

        Bug #25 root cause, fixed here. Until 2026-07-23 this method
        recognised exactly one controllable thing -- `penalty` -- so the
        entire cognitive layer had a one-word vocabulary: 201 principles,
        the knowledge graph and the causal engine all collapsed into a
        single scalar saying where to cut the feature ranking. "Use fewer
        features" is simply the wrong advice on some datasets, which is
        why connecting that one wire measured as a wash (+0.0002 mean).

        The rest of the vocabulary was already plumbed end to end and
        never used:
          - `uil_miner._build_matrix` flattens `action.classifier_config`
            into `config.<name>` columns, so the tree can already split on
            `config.sparse_l1_c`;
          - `optimizer._apply_overrides` already forwards `config.<name>`
            keys into `classifier.apply_config()`;
          - `SymbolicFormulaAdapter.apply_config` already accepts every one
            of `sparse_l1_c`, `use_rule_basis`, `use_stump_basis`,
            `use_neural_basis`, `boosting_stages`, `bagging_estimators`.
        Nothing in between ever EMITTED such a key. This does.

        Bounds, not assignments: a mined threshold is evidence about where
        regret rises, not a decree about where to sit. Emitting
        `config_max.<name>` / `config_min.<name>` (resolved against the
        live value in `_apply_overrides`) keeps the search free to move
        inside the constrained region -- and, unlike a hard assignment,
        does not set every architecture-race arm identically and collapse
        the race into one candidate scored N times.
        """
        # A rule's conditions are a CONJUNCTION -- one root-to-leaf path
        # of the tree -- so together they describe the REGION in which
        # regret is high, not a list of independent facts. Collect the
        # region per controllable feature first, then invert it once.
        # (Inverting each condition separately is what produced
        # `config_min.boosting_stages: 20.51` alongside
        # `config_max.boosting_stages: 16.5` -- an infeasible constraint,
        # floor above ceiling, which the actuator cannot satisfy and
        # would silently mangle.)
        regions: dict[str, dict] = {}
        for cond in conditions:
            feature = cond.get("feature", "")
            threshold = cond.get("threshold", 0)
            op = cond.get("op", "")

            # String thresholds come from v22 routing rules
            # (`dataset.name ==`, `route.domain ==`) and carry no
            # orderable direction to invert -- see bug #17.
            if not isinstance(threshold, (int, float)) or isinstance(threshold, bool):
                continue

            if feature.startswith("config."):
                param = feature.split(".", 1)[1]
                if not param or param in self.NON_CONSTRAINABLE_CONFIG:
                    continue
                keys = (f"config_max.{param}", f"config_min.{param}",
                        f"config_avoid.{param}")
            elif feature in self.PENALTY_FEATURES:
                keys = ("max_penalty", "min_penalty", "penalty_avoid")
            else:
                # state.* and any un-actuatable action field: context only.
                continue

            r = regions.setdefault(feature, {"lo": None, "hi": None, "keys": keys})
            # The bad region's LOWER edge comes from ">" / ">=" splits,
            # its UPPER edge from "<" / "<=". Two splits on the same side
            # narrow it; keep the narrower (the leaf's actual interval).
            if op in (">", ">="):
                lo = threshold if op == ">" else threshold - 0.01
                r["lo"] = lo if r["lo"] is None else max(r["lo"], lo)
            elif op in ("<", "<="):
                hi = threshold if op == "<" else threshold + 0.01
                r["hi"] = hi if r["hi"] is None else min(r["hi"], hi)

        override: dict = {}
        for r in regions.values():
            hi_key, lo_key, avoid_key = r["keys"]
            lo, hi = r["lo"], r["hi"]
            if lo is not None and hi is not None:
                if hi <= lo:
                    continue  # empty region: the path says nothing usable
                # Bad region is a bounded interval. Leaving it is possible
                # in either direction, and which one is better depends on
                # where the knob currently sits -- which only the actuator
                # knows. Hand it the interval and let it step out the
                # near side (optimizer._resolve_config_bounds).
                override[avoid_key] = [float(lo), float(hi)]
            elif lo is not None:
                # High regret ABOVE lo, unbounded -> impose a ceiling.
                override[hi_key] = float(lo)
            elif hi is not None:
                # High regret BELOW hi, unbounded -> impose a floor.
                override[lo_key] = float(hi)

        return override

    def _find_similar(
        self, principles: list[dict], rule: dict
    ) -> int | None:
        """Find an existing principle with similar conditions."""
        for i, p in enumerate(principles):
            if self._conditions_similar(p.get("conditions", []), rule.get("conditions", [])):
                return i
        return None

    def _conditions_similar(
        self, conds_a: list[dict], conds_b: list[dict]
    ) -> bool:
        """Check if two condition sets are similar (same features, close thresholds).

        The implementation lives in cognition/condition_match.py -- it was
        duplicated here, in editable_network and in journal_forgetting,
        and all three carried bug #17 simultaneously.
        """
        return condition_sets_similar(conds_a, conds_b)

    def _merge_evidence(self, existing: dict, new_rule: dict) -> None:
        """Merge new evidence into an existing principle."""
        existing["evidence_count"] = (
            existing.get("evidence_count", 0) + new_rule.get("evidence_count", 0)
        )
        # Update confidence (weighted average, biased toward new evidence)
        old_conf = existing.get("confidence", 0.5)
        new_conf = new_rule.get("confidence", 0.5)
        existing["confidence"] = min(0.99, 0.6 * old_conf + 0.4 * new_conf)

    def _apply_decay(self, principles: list[dict]) -> list[dict]:
        """Apply decay to principles that aren't helping.

        If times_helped / times_applied < 0.3 after 20+ applications,
        halve the confidence. If confidence drops below 0.3, remove.

        V20+.1: Also runs tier promotion/demotion after decay.
        """
        surviving = []
        for p in principles:
            applied = p.get("times_applied", 0)
            helped = p.get("times_helped", 0)

            if applied >= self.DECAY_MIN_APPLICATIONS:
                help_ratio = helped / max(applied, 1)
                if help_ratio < self.DECAY_HELP_RATIO:
                    old_conf = p.get("confidence", 0.5)
                    new_conf = old_conf * 0.5
                    p["confidence"] = new_conf
                    self._log_cell(
                        dict(p),
                        op="decay",
                        cause=f"help_ratio={help_ratio:.3f}",
                    )

            # Remove dead principles (but never remove exceptions)
            if p.get("confidence", 0) >= 0.30 or p.get("tier") == TIER_EXCEPTION:
                surviving.append(p)

        # V20+.1: Run tier promotion/demotion
        surviving = self.hierarchy.update_principle_tiers(surviving)

        return surviving

    def _ensure_file(self) -> None:
        """Ensure library file exists."""
        dirpath = os.path.dirname(self.library_path)
        if dirpath and not os.path.exists(dirpath):
            os.makedirs(dirpath, exist_ok=True)
        if not os.path.exists(self.library_path):
            with open(self.library_path, "w") as f:
                json.dump([], f)

    def _load(self) -> list[dict]:
        """Load principles from file.

        Repairs unsupported overrides on the way in (see
        sanitize_overrides) so principles minted before the derived-
        feature fix stop acting on knobs their conditions never mention.
        A no-op on healthy data; the repair reaches disk at the next
        _save, which every mutating path already performs.
        """
        try:
            with open(self.library_path, "r") as f:
                principles = json.load(f)
        except (json.JSONDecodeError, FileNotFoundError):
            return []
        for p in principles:
            if isinstance(p, dict):
                self.sanitize_overrides(p)
        return principles

    def _save(self, principles: list[dict]) -> None:
        """Save principles to file."""
        with open(self.library_path, "w") as f:
            json.dump(principles, f, indent=2, default=str)

    # ── V20+.1: Tier-Aware Methods ───────────────────────────────────

    def get_tier_summary(self) -> dict:
        """Get a summary of principle counts by tier."""
        return self.hierarchy.get_tier_summary(self._load())

    def create_exception(
        self,
        principle_id: str,
        dataset_name: str,
        working_overrides: dict,
    ) -> str | None:
        """Create a Tier 4 exception for a dataset that breaks a principle.

        Returns the exception principle ID, or None if the base principle
        was not found.
        """
        principles = self._load()
        base = None
        for p in principles:
            if p["principle_id"] == principle_id:
                base = p
                break

        if base is None:
            return None

        exception = self.hierarchy.create_exception_principle(
            base, dataset_name, working_overrides
        )
        principles.append(exception)
        self._save(principles)
        return exception["principle_id"]

    def check_quarantine(
        self, principle_id: str, dataset_name: str
    ) -> bool:
        """Check if a principle should be quarantined for a dataset."""
        principles = self._load()
        for p in principles:
            if p["principle_id"] == principle_id:
                return self.hierarchy.check_quarantine(p, dataset_name)
        return False

